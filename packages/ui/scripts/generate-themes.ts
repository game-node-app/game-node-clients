/**
 * Checks the git index, not the working tree: CI checks out a commit, so in CI
 * the index equals HEAD. Locally this still passes after `git add` (the commit
 * will contain the output) and fails when the generated files are untracked or
 * their staged content is stale.
 */
function assertGeneratedFilesAreCommitted(
  assets: { path: string; content: string }[],
): void {
  let repoRoot: string;
  try {
    repoRoot = execFileSync("git", ["rev-parse", "--show-toplevel"], {
      cwd: SCRIPT_DIR,
      encoding: "utf8",
    }).trim();
  } catch {
    fail(
      "Could not locate the git repository. `themes:check` needs git to verify " +
        "that the generated files are committed.",
    );
  }

  const relativeGeneratedDir = path
    .relative(repoRoot, GENERATED_DIR)
    .split(path.sep)
    .join("/");
  const untracked = execFileSync(
    "git",
    ["ls-files", "--others", "--exclude-standard", "--", relativeGeneratedDir],
    { cwd: repoRoot, encoding: "utf8" },
  ).trim();
  if (untracked) {
    fail(
      "Generated theme files are not tracked by git:\n" +
        `${untracked}\n` +
        "Run `pnpm themes:generate`, `git add` and commit the generated files.",
    );
  }

  for (const asset of assets) {
    const relativePath = path
      .relative(repoRoot, asset.path)
      .split(path.sep)
      .join("/");
    let indexedContent: string | null = null;
    try {
      indexedContent = execFileSync("git", ["show", `:${relativePath}`], {
        cwd: repoRoot,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
    } catch {
      indexedContent = null;
    }
    if (indexedContent === null) {
      fail(
        `${relativePath} is not added to git. ` +
          "Run `pnpm themes:generate`, `git add` and commit the generated files.",
      );
    }
    if (indexedContent !== asset.content) {
      fail(
        `${relativePath} is stale in the git index. ` +
          "Run `pnpm themes:generate` and stage the result before committing.",
      );
    }
  }
}

function main(): void {
  const assets = renderThemeAssets();
  const outputPaths = assets.map((asset) =>
    path.relative(process.cwd(), asset.path),
  );

  if (!CHECK_MODE) {
    mkdirSync(GENERATED_DIR, { recursive: true });
    for (const asset of assets) {
      writeFileSync(asset.path, asset.content, "utf8");
    }
    console.log(`Generated ${outputPaths.join(", ")}`);
    return;
  }

  const stale: string[] = [];
  for (const asset of assets) {
    const relativePath = path.relative(process.cwd(), asset.path);
    if (!existsSync(asset.path)) {
      stale.push(`${relativePath} is missing`);
      continue;
    }
    const current = readFileSync(asset.path, "utf8");
    if (current !== asset.content) stale.push(`${relativePath} is stale`);
  }
  if (stale.length) {
    fail(
      `${stale.join(", ")}.\nRun \`pnpm themes:generate\` and commit the result.`,
    );
  }
  assertGeneratedFilesAreCommitted(assets);
  console.log("Generated theme files are up to date.");
}

try {
  main();
} catch (error) {
  console.error(
    error instanceof Error
      ? `${CHECK_MODE ? "themes:check" : "themes:generate"}: ${error.message}`
      : error,
  );
  process.exitCode = 1;
}
