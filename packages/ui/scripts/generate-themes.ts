function fail(message: string): never {
  throw new Error(message);
}

function parseColor(value: string, context: string): Color {
  const parsed = parse(value);
  if (!parsed) fail(`${context}: "${value}" is not a valid CSS color.`);
  return parsed;
}

function assertHexToken(
  definition: ThemeDefinition,
  key: ThemeTokenKey,
): string {
  const value = definition.tokens[key];
  if (typeof value !== "string" || !value.trim()) {
    fail(`${definition.id}.tokens.${key} must be a non-empty string.`);
  }
  if (!/^#[0-9a-f]{6}$/i.test(value)) {
    fail(
      `${definition.id}.tokens.${key} must be a #RRGGBB color (got "${value}"). ` +
        "Native chrome consumes these tokens as hex.",
    );
  }
  parseColor(value, `${definition.id}.tokens.${key}`);
  return value;
}

function clamp(value: number, min = 0, max = 1): number {
  return Math.min(max, Math.max(min, value));
}

/** Mix an OKLCH color toward white, keeping the hue. */
function lighten(value: string, amount: number): string {
  const color = oklch(parseColor(value, "lighten"));
  if (!color) fail(`lighten: could not read "${value}".`);
  return formatHex({
    ...color,
    l: clamp(color.l + (1 - color.l) * amount),
    c: Math.max(0, color.c * (1 - amount * 0.6)),
  });
}

/** Mix an OKLCH color toward black, keeping the hue. */
function darken(value: string, amount: number): string {
  const color = oklch(parseColor(value, "darken"));
  if (!color) fail(`darken: could not read "${value}".`);
  return formatHex({
    ...color,
    l: clamp(color.l * (1 - amount)),
    c: Math.max(0, color.c * (1 - amount * 0.4)),
  });
}

/** sRGB interpolation, used for translucent-looking surfaces. */
function blend(base: string, overlay: string, amount: number): string {
  const from = rgb(parseColor(base, "blend"));
  const to = rgb(parseColor(overlay, "blend"));
  if (!from || !to) fail(`blend: could not read "${base}" or "${overlay}".`);
  return formatHex({
    mode: "rgb",
    r: from.r + (to.r - from.r) * amount,
    g: from.g + (to.g - from.g) * amount,
    b: from.b + (to.b - from.b) * amount,
  });
}

function rgba(value: string, alpha: number): string {
  const color = rgb(parseColor(value, "rgba"));
  if (!color) fail(`rgba: could not read "${value}".`);
  const channel = (component: number) => Math.round(component * 255);
  return `rgba(${channel(color.r)}, ${channel(color.g)}, ${channel(color.b)}, ${alpha})`;
}

function rgbTriplet(value: string): string {
  const color = rgb(parseColor(value, "rgb"));
  if (!color) fail(`rgb: could not read "${value}".`);
  const channel = (component: number) => Math.round(component * 255);
  return `${channel(color.r)},${channel(color.g)},${channel(color.b)}`;
}

function luminance(value: string): number {
  const color = rgb(parseColor(value, "luminance"));
  if (!color) fail(`luminance: could not read "${value}".`);
  const channel = (component: number) =>
    component <= 0.03928
      ? component / 12.92
      : ((component + 0.055) / 1.055) ** 2.4;
  return (
    0.2126 * channel(color.r) +
    0.7152 * channel(color.g) +
    0.0722 * channel(color.b)
  );
}

function contrastRatio(a: string, b: string): number {
  const first = luminance(a);
  const second = luminance(b);
  const lighter = Math.max(first, second);
  const darker = Math.min(first, second);
  return (lighter + 0.05) / (darker + 0.05);
}

function autoContrast(background: string): string {
  // Named CSS colors keep the contrast math out of the hard-coded-color rule.
  return contrastRatio(background, "black") >=
    contrastRatio(background, "white")
    ? "black"
    : "white";
}

function buildScale(
  defaults: (step: ThemeScaleStep) => string,
  overrides: ThemeScaleOverrides | undefined,
): ResolvedScale {
  return Object.fromEntries(
    SCALE_STEPS.map((step) => [step, overrides?.[step] ?? defaults(step)]),
  ) as ResolvedScale;
}

function buildPaper(
  defaults: (step: ThemePaperStep) => string,
  overrides: ThemePaperOverrides | undefined,
): ResolvedPaper {
  return Object.fromEntries(
    PAPER_STEPS.map((step) => [step, overrides?.[step] ?? defaults(step)]),
  ) as ResolvedPaper;
}

function brandDefaults(accent: string) {
  const lightSteps = new Map<ThemeScaleStep, number>([
    [0, 0.85],
    [1, 0.7],
    [2, 0.5],
    [3, 0.3],
    [4, 0.15],
  ]);
  const darkSteps = new Map<ThemeScaleStep, number>([
    [6, 0.08],
    [7, 0.18],
    [8, 0.28],
    [9, 0.38],
  ]);
  return (step: ThemeScaleStep): string => {
    if (step === 5) return accent;
    const light = lightSteps.get(step);
    if (light !== undefined) return lighten(accent, light);
    const dark = darkSteps.get(step);
    if (dark === undefined) fail(`brandDefaults: unhandled step ${step}.`);
    return darken(accent, dark);
  };
}

function paperDefaults(surface: string, background: string) {
  const lightSteps = new Map<ThemePaperStep, number>([
    [0, 0],
    [1, 0.08],
    [2, 0.045],
    [3, 0.03],
    [4, 0.07],
    [5, 0.04],
    [6, 0.06],
    [8, 0.035],
  ]);
  return (step: ThemePaperStep): string => {
    if (step === 7) return background;
    const amount = lightSteps.get(step);
    if (amount === undefined) fail(`paperDefaults: unhandled step ${step}.`);
    if (amount === 0) return surface;
    return lighten(surface, amount);
  };
}

function darkDefaults(text: string, textMuted: string, surface: string) {
  return (step: ThemeScaleStep): string => {
    if (step === 0) return text;
    if (step === 1) return blend(text, surface, 0.25);
    if (step === 2) return textMuted;
    if (step === 9) return surface;
    const lightSteps: Record<number, number> = {
      3: 0.38,
      4: 0.18,
      5: 0.14,
      6: 0.1,
      7: 0.06,
      8: 0.03,
    };
    return lighten(surface, lightSteps[step]);
  };
}

