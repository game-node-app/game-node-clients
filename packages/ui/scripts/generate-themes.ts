function resolveIonicColor(
  name: ThemeIonicColorName,
  accent: string,
  accentContrast: string,
  tertiary: string,
  tokens: {
    success: string;
    warning: string;
    danger: string;
    background: string;
    surface: string;
  },
  override: Partial<ThemeIonicColorSet> | undefined,
): ThemeIonicColorSet {
  const defaults: Record<ThemeIonicColorName, string> = {
    primary: accent,
    secondary: lighten(accent, 0.2),
    tertiary,
    success: tokens.success,
    warning: tokens.warning,
    danger: tokens.danger,
    light: lighten(tokens.background, 0.9),
    medium: lighten(tokens.surface, 0.35),
    dark: tokens.background,
  };
  const base = override?.base ?? defaults[name];
  const contrast =
    override?.contrast ??
    (name === "primary" ? accentContrast : autoContrast(base));
  return {
    base,
    contrast,
    shade: override?.shade ?? darken(base, 0.12),
    tint: override?.tint ?? lighten(base, 0.1),
  };
}

function sortDefinitions(
  definitions: readonly ThemeDefinition[],
): ThemeDefinition[] {
  if (!definitions.length) fail("No theme definitions registered.");
  const ids = new Set<string>();
  for (const definition of definitions) {
    if (!/^[a-z][a-z0-9-]*$/.test(definition.id)) {
      fail(
        `Invalid theme id "${definition.id}": use lowercase letters, digits and dashes.`,
      );
    }
    if (!definition.labelKey.trim()) {
      fail(`Theme "${definition.id}" must define a labelKey.`);
    }
    if (
      definition.colorScheme !== "dark" &&
      definition.colorScheme !== "light"
    ) {
      fail(
        `Theme "${definition.id}" has an invalid colorScheme "${definition.colorScheme}".`,
      );
    }
    if (
      definition.experience !== undefined &&
      definition.experience !== "default" &&
      definition.experience !== "console"
    ) {
      fail(
        `Theme "${definition.id}" has an invalid experience "${definition.experience}".`,
      );
    }
    if (definition.screens !== undefined && !definition.screens.trim()) {
      fail(`Theme "${definition.id}" has an empty screens id.`);
    }
    if (!definition.radius.trim() || !definition.font.trim()) {
      fail(`Theme "${definition.id}" must define radius and font.`);
    }
    if (ids.has(definition.id)) fail(`Duplicate theme id "${definition.id}".`);
    ids.add(definition.id);
  }
  if (!ids.has(DEFAULT_REGISTERED_THEME_ID)) {
    fail(
      `DEFAULT_REGISTERED_THEME_ID "${DEFAULT_REGISTERED_THEME_ID}" is not registered.`,
    );
  }
  const sorted = [...definitions].sort((a, b) =>
    a.id < b.id ? -1 : a.id > b.id ? 1 : 0,
  );
  const defaultIndex = sorted.findIndex(
    (definition) => definition.id === DEFAULT_REGISTERED_THEME_ID,
  );
  const [defaultTheme] = sorted.splice(defaultIndex, 1);
  return [defaultTheme, ...sorted];
}

function renderCss(themes: ResolvedTheme[]): string {
  const lines: string[] = [`/* ${HEADER[0]} */`, `/* ${HEADER[1]} */`, ""];
  for (const theme of themes) {
    const isDefault = theme.definition.id === DEFAULT_REGISTERED_THEME_ID;
    const selector = isDefault
      ? `:root,\n:root[data-theme="${theme.definition.id}"]`
      : `:root[data-theme="${theme.definition.id}"]`;
    lines.push(`${selector} {`);
    for (const [name, value] of theme.variables) {
      lines.push(`  ${name}: ${value};`);
    }
    lines.push("}", "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

