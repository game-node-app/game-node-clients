// @vitest-environment node
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const read = (path: string) =>
  readFileSync(
    new URL(`../../../../packages/ui/${path}`, import.meta.url),
    "utf8",
  );

describe("theme pack boundaries", () => {
  it("keeps pack entries out of the package barrels", () => {
    const themeBarrel = read("src/theme/index.ts");
    const experiencesBarrel = read("src/theme/experiences/index.ts");
    const packsBarrel = read("src/theme/packs/index.ts");
    const themesBarrel = read("src/theme/themes/index.ts");

    // A barrelsby regeneration must not add eager exports of the pack folders.
    expect(themeBarrel).not.toMatch(/export .*experiences\/console/);
    expect(themeBarrel).not.toMatch(/export .*xbox\/screens/);
    expect(experiencesBarrel).not.toMatch(/export .*"\.\/console"/);
    expect(packsBarrel).not.toMatch(/export .*"\.\/anchors/);
    expect(themesBarrel).not.toMatch(/export .*screens\/index/);
    expect(themesBarrel).not.toMatch(/export .*xbox\/screens/);
  });

  it("excludes pack folders from barrelsby", () => {
    const config = JSON.parse(read("barrelsby.json")) as {
      exclude?: string[];
    };
    const patterns = (config.exclude ?? []).map((value) => new RegExp(value));

    expect(
      patterns.some((pattern) =>
        pattern.test("/repo/src/theme/experiences/console/index.ts"),
      ),
    ).toBe(true);
    expect(
      patterns.some((pattern) =>
        pattern.test("/repo/src/theme/themes/xbox/screens/index.ts"),
      ),
    ).toBe(true);
    expect(
      patterns.some((pattern) =>
        pattern.test("/repo/src/theme/packs/anchors/console.tsx"),
      ),
    ).toBe(true);
    expect(
      patterns.some((pattern) =>
        pattern.test("/repo/src/theme/experiences/registry.ts"),
      ),
    ).toBe(false);
  });

  it("loads packs only through static import() boundaries", () => {
    const provider = read("src/theme/AppThemeProvider.tsx");
    const experienceRegistry = read("src/theme/experiences/registry.ts");
    const screensRegistry = read("src/theme/themes/screens-registry.ts");

    expect(experienceRegistry).toContain('import("./console")');
    expect(screensRegistry).toContain('import("./xbox/screens")');
    expect(experienceRegistry).not.toMatch(/^\s*import .*console/m);
    expect(screensRegistry).not.toMatch(/^\s*import .*xbox\/screens/m);
    expect(provider).not.toMatch(/from .*experiences\/console/);
    expect(provider).not.toMatch(/from .*themes\/xbox\/screens/);
  });

  it("keeps the hand-written pack entries intact during barrel generation", () => {
    const consolePack = read("src/theme/experiences/console/index.ts");
    const screensPack = read("src/theme/themes/xbox/screens/index.ts");

    expect(consolePack).toContain("export const presenters");
    expect(screensPack).toContain("export const presenters");
    // barrelsby purges index files that carry its header; the pack entries must
    // stay hand-written so a regeneration cannot delete them.
    expect(consolePack).not.toContain(
      "@file Automatically generated by barrelsby",
    );
    expect(screensPack).not.toContain(
      "@file Automatically generated by barrelsby",
    );
  });
});
