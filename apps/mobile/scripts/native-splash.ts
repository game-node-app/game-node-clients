import { existsSync, readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  THEME_CATALOG,
  type ThemeCatalogEntry,
} from "../../../packages/ui/src/theme/generated/catalog";

/**
 * Renders the Android launch-splash resources from the generated theme catalog
 * (`native.splash`), so a theme needs no hand-written native code. Used by
 * `generate-native-splash.ts` (CLI) and by `src/theme/splash-palette.test.ts`.
 *
 * Output (all under `android/app/src/main`):
 * - `res/values/splash_themes.xml`: the default theme's `splash_*` colors
 *   (used by the manifest launch theme, `splash_launch.xml` and
 *   `AppTheme.NoActionBar`), `splash_<id>_*` colors and an
 *   `AppTheme.NoActionBarLaunch.<Id>` system-splash style per other theme.
 * - `res/drawable/ic_splash_logo_<id>.xml`: `ic_splash_logo.xml` (the
 *   hand-written geometry template) with the theme's colors.
 * - `java/app/gamenode/splash/SplashThemes.java`: theme id -> resources.
 */

export const ANDROID_MAIN_DIR = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "android",
  "app",
  "src",
  "main",
);

const VALUES_PATH = "res/values/splash_themes.xml";
const DRAWABLE_DIR = "res/drawable";
const LOGO_TEMPLATE_PATH = `${DRAWABLE_DIR}/ic_splash_logo.xml`;
const JAVA_PATH = "java/app/gamenode/splash/SplashThemes.java";
/** Marks files this generator owns, so stale ones can be pruned safely. */
const GENERATED_MARKER =
  "Auto-generated by apps/mobile/scripts/native-splash.ts";
const GENERATED_LOGO_PATTERN = /^ic_splash_logo_[a-z0-9_]+\.xml$/;

export type NativeSplashFile = { path: string; content: string };

type SplashTheme = {
  id: string;
  resource: string;
  pascal: string;
  isDefault: boolean;
  background: string;
  brand: string;
  logoInner: string;
};

function fail(message: string): never {
  throw new Error(message);
}

function hex(themeId: string, name: string, value: string): string {
  if (!/^#[0-9a-f]{6}$/i.test(value)) {
    fail(
      `Theme "${themeId}" native.splash.${name} must be #RRGGBB (got "${value}").`,
    );
  }
  return value.toUpperCase();
}

function toSplashThemes(catalog: readonly ThemeCatalogEntry[]): SplashTheme[] {
  const themes = catalog.map((entry) => ({
    id: entry.id,
    // theme ids are lowercase letters, digits and dashes
    resource: entry.id.replace(/-/g, "_"),
    pascal: entry.id
      .split("-")
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(""),
    isDefault: entry.isDefault,
    background: hex(entry.id, "background", entry.native.splash.background),
    brand: hex(entry.id, "brand", entry.native.splash.brand),
    logoInner: hex(entry.id, "logoInner", entry.native.splash.logoInner),
  }));
  if (themes.filter((theme) => theme.isDefault).length !== 1) {
    fail("The theme catalog must contain exactly one default theme.");
  }
  // deterministic: default first, then by id
  return themes.sort(
    (a, b) =>
      Number(b.isDefault) - Number(a.isDefault) || a.id.localeCompare(b.id),
  );
}

function xmlHeader(): string {
  return [
    "<!--",
    `    ${GENERATED_MARKER}. Do not edit manually.`,
    "    Run `pnpm splash:generate` (or `pnpm themes:generate` from the repo root) after changing a theme.",
    "-->",
  ].join("\n");
}

function renderValues(themes: readonly SplashTheme[]): string {
  const lines: string[] = [
    '<?xml version="1.0" encoding="utf-8"?>',
    xmlHeader(),
    "<resources>",
  ];
  for (const theme of themes) {
    const prefix = theme.isDefault ? "splash" : `splash_${theme.resource}`;
    lines.push(
      theme.isDefault
        ? `    <!-- ${theme.id} (default): manifest launch theme, splash_launch.xml and AppTheme.NoActionBar. -->`
        : `    <!-- ${theme.id} -->`,
      `    <color name="${prefix}_background">${theme.background}</color>`,
      `    <color name="${prefix}_brand">${theme.brand}</color>`,
      `    <color name="${prefix}_logo_inner">${theme.logoInner}</color>`,
    );
  }
  for (const theme of themes.filter((entry) => !entry.isDefault)) {
    lines.push(
      "",
      `    <!-- System splash for "${theme.id}" (Android 13+: MainActivity#applyLaunchTheme; older versions keep the default). -->`,
      `    <style name="AppTheme.NoActionBarLaunch.${theme.pascal}">`,
      `        <item name="windowSplashScreenBackground">@color/splash_${theme.resource}_background</item>`,
      `        <item name="windowSplashScreenAnimatedIcon">@drawable/ic_splash_logo_${theme.resource}</item>`,
      "    </style>",
    );
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

function renderLogo(template: string, theme: SplashTheme): string {
  const body = template.replace(/^<\?xml[^>]*\?>\s*<!--[\s\S]*?-->\s*/, "");
  if (body === template || !body.includes("@color/splash_brand")) {
    fail(
      `${LOGO_TEMPLATE_PATH} must start with the XML declaration and a comment, and use @color/splash_brand / @color/splash_logo_inner.`,
    );
  }
  const themed = body
    .replaceAll("@color/splash_brand", `@color/splash_${theme.resource}_brand`)
    .replaceAll(
      "@color/splash_logo_inner",
      `@color/splash_${theme.resource}_logo_inner`,
    );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!--",
    `    ${GENERATED_MARKER}. Do not edit manually.`,
    `    ic_splash_logo.xml in the "${theme.id}" theme's splash colors (same geometry: edit the template, then run \`pnpm splash:generate\`).`,
    "-->",
    themed,
  ].join("\n");
}

function renderJava(themes: readonly SplashTheme[]): string {
  const defaultTheme = themes.find((theme) => theme.isDefault)!;
  const cases = themes
    .filter((theme) => !theme.isDefault)
    .map(
      (theme) =>
        `            case "${theme.id}":\n` +
        `                return new SplashThemes(\n` +
        `                    R.color.splash_${theme.resource}_background,\n` +
        `                    R.color.splash_${theme.resource}_brand,\n` +
        `                    R.color.splash_${theme.resource}_logo_inner,\n` +
        `                    R.style.AppTheme_NoActionBarLaunch_${theme.pascal}\n` +
        `                );`,
    );
  return `// ${GENERATED_MARKER}. Do not edit manually.
// Run \`pnpm splash:generate\` (or \`pnpm themes:generate\` from the repo root) after changing a theme.
package app.gamenode.splash;

import androidx.annotation.ColorRes;
import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.annotation.StyleRes;
import app.gamenode.R;

/** Splash resources per theme id, generated from the theme catalog (\`native.splash\`). */
final class SplashThemes {

    @ColorRes
    final int background;

    @ColorRes
    final int brand;

    @ColorRes
    final int logoInner;

    /** System-splash launch theme with the same colors. */
    @StyleRes
    final int launchTheme;

    private SplashThemes(@ColorRes int background, @ColorRes int brand, @ColorRes int logoInner, @StyleRes int launchTheme) {
        this.background = background;
        this.brand = brand;
        this.logoInner = logoInner;
        this.launchTheme = launchTheme;
    }

    /** The default theme (${defaultTheme.id}), also used for an unknown or missing id. */
    @NonNull
    static SplashThemes defaultTheme() {
        return new SplashThemes(
            R.color.splash_background,
            R.color.splash_brand,
            R.color.splash_logo_inner,
            R.style.AppTheme_NoActionBarLaunch
        );
    }

    @NonNull
    static SplashThemes forId(@Nullable String themeId) {
        if (themeId == null) return defaultTheme();
        switch (themeId) {
${cases.join("\n")}
            default:
                return defaultTheme();
        }
    }
}
`;
}

/** Every generated file for the catalog (default: the checked-in one). */
export function renderNativeSplashFiles(
  catalog: readonly ThemeCatalogEntry[] = THEME_CATALOG,
  mainDir: string = ANDROID_MAIN_DIR,
): NativeSplashFile[] {
  const themes = toSplashThemes(catalog);
  const templatePath = path.join(mainDir, LOGO_TEMPLATE_PATH);
  if (!existsSync(templatePath)) fail(`Missing ${LOGO_TEMPLATE_PATH}.`);
  const template = readFileSync(templatePath, "utf8");
  return [
    { path: VALUES_PATH, content: renderValues(themes) },
    ...themes
      .filter((theme) => !theme.isDefault)
      .map((theme) => ({
        path: `${DRAWABLE_DIR}/ic_splash_logo_${theme.resource}.xml`,
        content: renderLogo(template, theme),
      })),
    { path: JAVA_PATH, content: renderJava(themes) },
  ];
}

/** Generated drawables on disk that the catalog no longer asks for. */
export function findStaleNativeSplashFiles(
  expected: readonly NativeSplashFile[],
  mainDir: string = ANDROID_MAIN_DIR,
): string[] {
  const keep = new Set(expected.map((file) => file.path));
  const dir = path.join(mainDir, DRAWABLE_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => GENERATED_LOGO_PATTERN.test(name))
    .map((name) => `${DRAWABLE_DIR}/${name}`)
    .filter((relative) => !keep.has(relative))
    .filter((relative) =>
      readFileSync(path.join(mainDir, relative), "utf8").includes(
        GENERATED_MARKER,
      ),
    );
}

/** Paths whose content on disk differs from the generated output, or stale files. */
export function checkNativeSplashFiles(
  mainDir: string = ANDROID_MAIN_DIR,
  catalog: readonly ThemeCatalogEntry[] = THEME_CATALOG,
): string[] {
  const files = renderNativeSplashFiles(catalog, mainDir);
  const outdated = files
    .filter((file) => {
      const target = path.join(mainDir, file.path);
      return (
        !existsSync(target) || readFileSync(target, "utf8") !== file.content
      );
    })
    .map((file) => file.path);
  return [...outdated, ...findStaleNativeSplashFiles(files, mainDir)];
}
